import Foundation
import Security

final class RetroAchievementsCredentialStore {

    static let shared = RetroAchievementsCredentialStore()

    private static let keychainService = "org.openemu.Bit.RetroAchievements"
    private static let usernameDefaultsKey = "retroAchievementsUsername"

    var username: String? {
        UserDefaults.standard.string(forKey: Self.usernameDefaultsKey)
    }

    var token: String? {
        loadToken()
    }

    var isLoggedIn: Bool {
        username != nil && token != nil
    }

    func save(username: String, token: String) {
        UserDefaults.standard.set(username, forKey: Self.usernameDefaultsKey)

        let data = token.data(using: .utf8)!

        let query: [String: Any] = [
            kSecClass as String: kSecClassGenericPassword,
            kSecAttrService as String: Self.keychainService,
            kSecAttrAccount as String: "token",
        ]

        SecItemDelete(query as CFDictionary)

        var addQuery = query
        addQuery[kSecValueData as String] = data
        SecItemAdd(addQuery as CFDictionary, nil)
    }

    func clear() {
        UserDefaults.standard.removeObject(forKey: Self.usernameDefaultsKey)

        let query: [String: Any] = [
            kSecClass as String: kSecClassGenericPassword,
            kSecAttrService as String: Self.keychainService,
            kSecAttrAccount as String: "token",
        ]
        SecItemDelete(query as CFDictionary)
    }

    private func loadToken() -> String? {
        let query: [String: Any] = [
            kSecClass as String: kSecClassGenericPassword,
            kSecAttrService as String: Self.keychainService,
            kSecAttrAccount as String: "token",
            kSecReturnData as String: true,
        ]

        var result: AnyObject?
        let status = SecItemCopyMatching(query as CFDictionary, &result)

        guard status == errSecSuccess,
              let data = result as? Data,
              let token = String(data: data, encoding: .utf8) else {
            return nil
        }

        return token
    }
}
